        [MenuItem("Palette Shaper/3. Generate Sprites", priority = 3)]
        public static void GenerateSprites()
        {
            if (!AssetDatabase.IsValidFolder(SpritesRoot)) CreateFolders(new StringBuilder());
            string projectDir = Directory.GetParent(Application.dataPath).FullName;
            var errors = new List<string>();
            var written = new List<string>();

            foreach (var obsolete in ObsoleteSprites)
            {
                string obsoletePath = $"{SpritesRoot}/{obsolete}.png";
                if (AssetDatabase.LoadAssetAtPath<Texture2D>(obsoletePath) != null) AssetDatabase.DeleteAsset(obsoletePath);
            }

            foreach (var ext in ExternalSprites)
            {
                string extPath = $"{SpritesRoot}/{ext}.png";
                if (File.Exists(Path.Combine(projectDir, extPath)))
                    AssetDatabase.ImportAsset(extPath, ImportAssetOptions.ForceSynchronousImport | ImportAssetOptions.ForceUpdate);
            }

            foreach (var (name, frames) in SpriteData)
            {
                if (!SpriteSizeSpec.TryGetValue(name, out var spec)) { errors.Add($"{name}: 규격표에 없음"); continue; }
                if (frames.Length != spec.frames) { errors.Add($"{name}: 프레임 {frames.Length} ≠ 규격 {spec.frames}"); continue; }
                bool shapeOk = frames.All(f => f.Length == spec.h && f.All(r => r.Length == spec.w));
                if (!shapeOk) { errors.Add($"{name}: 프레임 크기가 {spec.w}x{spec.h}가 아님"); continue; }

                int texW = spec.w * spec.frames, texH = spec.h;
                var tex = new Texture2D(texW, texH, TextureFormat.RGBA32, false);
                var pixels = new Color32[texW * texH];
                bool charOk = true;
                for (int f = 0; f < frames.Length && charOk; f++)
                {
                    for (int row = 0; row < spec.h && charOk; row++)
                    {
                        string line = frames[f][row];
                        int y = spec.h - 1 - row; // 문자맵은 위→아래, 텍스처는 아래→위
                        for (int x = 0; x < spec.w; x++)
                        {
                            char c = line[x];
                            Color32 col;
                            if (c == '.') col = new Color32(0, 0, 0, 0);
                            else if (!PixelKey.TryGetValue(c, out col)) { errors.Add($"{name}: 알 수 없는 픽셀 문자 '{c}'"); charOk = false; break; }
                            pixels[y * texW + f * spec.w + x] = col;
                        }
                    }
                }
                if (!charOk) { Object.DestroyImmediate(tex); continue; }
                tex.SetPixels32(pixels);
                tex.Apply();
                string assetPath = $"{SpritesRoot}/{name}.png";
                File.WriteAllBytes(Path.Combine(projectDir, assetPath), tex.EncodeToPNG());
                Object.DestroyImmediate(tex);
                written.Add(assetPath);
            }

            foreach (var p in written)
                AssetDatabase.ImportAsset(p, ImportAssetOptions.ForceSynchronousImport | ImportAssetOptions.ForceUpdate);

            errors.AddRange(VerifyGeneratedSprites(projectDir));
            int spriteCount = written.Sum(p => AssetDatabase.LoadAllAssetsAtPath(p).OfType<Sprite>().Count());
            if (errors.Count == 0)
                Debug.Log($"{LogTag}[Sprites] ALL PASS: PNG {written.Count}개, 스프라이트 {spriteCount}개 생성/검증 완료");
            else
            {
                Debug.LogError($"{LogTag}[Sprites] FAILED: 문제 {errors.Count}건");
                foreach (var e in errors) Debug.LogError($"{LogTag}[Sprites] {e}");
            }
        }

        /// <summary>디스크의 PNG와 임포트 결과를 명세와 대조한다.</summary>
        static List<string> VerifyGeneratedSprites(string projectDir)
        {
            var errors = new List<string>();
            var allowed = new HashSet<Color32>(PixelKey.Values, new Color32Comparer());
            var artPalette = new HashSet<Color32>(new Color32Comparer());
            string hexPath = Path.Combine(projectDir, "art", "palette.hex");
            if (File.Exists(hexPath))
            {
                foreach (var line in File.ReadAllLines(hexPath))
                {
                    string h = line.Trim().TrimStart('#');
                    if (h.Length == 6 && ColorUtility.TryParseHtmlString("#" + h, out Color c)) artPalette.Add((Color32)c);
                }
            }
            else errors.Add("art/palette.hex 없음");
            foreach (var kv in SpriteSizeSpec)
            {
                string assetPath = $"{SpritesRoot}/{kv.Key}.png";
                string full = Path.Combine(projectDir, assetPath);
                if (!File.Exists(full)) { errors.Add($"{kv.Key}: 파일 없음"); continue; }

                var tex = new Texture2D(2, 2, TextureFormat.RGBA32, false);
                tex.LoadImage(File.ReadAllBytes(full));
                int expW = kv.Value.w * kv.Value.frames, expH = kv.Value.h;
                if (tex.width != expW || tex.height != expH) errors.Add($"{kv.Key}: 크기 {tex.width}x{tex.height} ≠ {expW}x{expH}");
                bool artPal = ExternalSprites.Contains(kv.Key); // 잔상 포함 전부 art/palette.hex 기준 (2026-11-20)
                var check = artPal ? artPalette : allowed;
                int bad = tex.GetPixels32().Count(c => c.a != 0 && !check.Contains(c));
                if (bad > 0) errors.Add($"{kv.Key}: 팔레트 밖 픽셀 {bad}개 ({(artPal ? "art/palette.hex" : "게임 팔레트")} 기준)");
                if (ExternalSprites.Contains(kv.Key))
                {
                    int semi = tex.GetPixels32().Count(c => c.a != 0 && c.a != 255);
                    if (semi > 0) errors.Add($"{kv.Key}: 반투명 픽셀 {semi}개");
                }
                Object.DestroyImmediate(tex);

                var ti = AssetImporter.GetAtPath(assetPath) as TextureImporter;
                if (ti == null) { errors.Add($"{kv.Key}: TextureImporter 없음"); continue; }
                if (ti.spritePixelsPerUnit != GameConstants.PIXELS_PER_UNIT) errors.Add($"{kv.Key}: PPU {ti.spritePixelsPerUnit}");
                if (ti.filterMode != FilterMode.Point) errors.Add($"{kv.Key}: Filter {ti.filterMode}");
                if (ti.textureCompression != TextureImporterCompression.Uncompressed) errors.Add($"{kv.Key}: Compression {ti.textureCompression}");

                var sprites = AssetDatabase.LoadAllAssetsAtPath(assetPath).OfType<Sprite>().ToArray();
                if (sprites.Length != kv.Value.frames) errors.Add($"{kv.Key}: 슬라이스 {sprites.Length} ≠ {kv.Value.frames}");
                bool isPlayer = kv.Key.StartsWith("Spr_Player_");
                var expPivot = isPlayer ? new Vector2(kv.Value.w * 0.5f, 0f) : new Vector2(kv.Value.w * 0.5f, kv.Value.h * 0.5f);
                foreach (var s in sprites)
                {
                    if (s.rect.width != kv.Value.w || s.rect.height != kv.Value.h) errors.Add($"{s.name}: rect {s.rect.width}x{s.rect.height}");
                    if (s.pivot != expPivot) errors.Add($"{s.name}: pivot {s.pivot} ≠ {expPivot}");
                }
            }
            return errors;
        }

        class Color32Comparer : IEqualityComparer<Color32>
        {
            public bool Equals(Color32 a, Color32 b) => a.r == b.r && a.g == b.g && a.b == b.b && a.a == b.a;
            public int GetHashCode(Color32 c) => (c.r << 24) | (c.g << 16) | (c.b << 8) | c.a;
        }

