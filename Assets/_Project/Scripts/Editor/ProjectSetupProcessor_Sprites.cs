        static string[][] BuildFontFrames()
        {
            var frames = new List<string[]>();
            foreach (char ch in GameConstants.UI_FONT_GLYPHS)
            {
                string bits = FontBits[ch];
                var rowsOut = new string[8];
                for (int y = 0; y < 8; y++)
                {
                    var sb = new StringBuilder();
                    for (int x = 0; x < 6; x++)
                        sb.Append(y < 7 && x < 5 && bits[y * 5 + x] == '1' ? 'I' : '.');
                    rowsOut[y] = sb.ToString();
                }
                frames.Add(rowsOut);
            }
            return frames.ToArray();
        }

